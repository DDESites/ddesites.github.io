/* Calcula o frete simulado pelo primeiro dígito do CEP */
function calcularFrete(cep) {
  const d = Number(String(cep).replace(/\D/g, "").charAt(0));
  if (d >= 1 && d <= 4) return { valor: 19.9, prazo: "2 a 4 dias úteis", regiao: "Sudeste" };
  if (d === 5 || d === 6) return { valor: 22.9, prazo: "3 a 5 dias úteis", regiao: "Centro-Oeste e Sul" };
  return { valor: 27.9, prazo: "5 a 9 dias úteis", regiao: "Norte e Nordeste" };
}
